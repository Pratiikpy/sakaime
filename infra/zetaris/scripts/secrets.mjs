#!/usr/bin/env node
// Creates the secrets the Zetaris stack needs in the repository .env (gitignored) when they are missing, and leaves
// every existing line untouched. Values are never printed. Usage: node infra/zetaris/scripts/secrets.mjs [--check]
//
// Passwords that Zetaris validates (at least 8 characters, a lower case letter, an upper case letter, a digit and one of
// $ @ ! % * ? &) are built to that rule. '$' is avoided because compose and shells expand it. Database passwords are
// letters and digits only because they are embedded in JDBC URLs.

import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const envPath = join(root, '.env');
const checkOnly = process.argv.includes('--check');

const hex = (bytes) => randomBytes(bytes).toString('hex');
const platformPassword = () => `Sk${hex(9)}A@7`; // upper S, lower k and hex, digits, upper A, '@'
const plainPassword = () => `${hex(16)}`;

const generated = {
  SAKAIME_ZETARIS_PG_PASSWORD: plainPassword,
  SAKAIME_ZETARIS_ADMIN_PASSWORD: platformPassword,
  SAKAIME_HOSPITAL_PG_PASSWORD: plainPassword,
  // Identities created by scripts/seed.mjs. Emails are not secret but live here so the scripts have one source.
  SAKAIME_ZETARIS_READER_EMAIL: () => 'agent-reader@sakaime.example',
  SAKAIME_ZETARIS_READER_PASSWORD: platformPassword,
  SAKAIME_ZETARIS_REVIEWER_EMAIL: () => 'reviewer-unassigned@sakaime.example',
  SAKAIME_ZETARIS_REVIEWER_PASSWORD: platformPassword,
  SAKAIME_ZETARIS_ASSIGNED_EMAIL: () => 'reviewer-assigned@sakaime.example',
  SAKAIME_ZETARIS_ASSIGNED_PASSWORD: platformPassword,
};
const required = ['ZETARIS_REGISTRY', 'ZETARIS_REGISTRY_USER', 'ZETARIS_REGISTRY_PASSWORD'];

const text = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
const present = new Set(
  text
    .split(/\r?\n/)
    .map((l) => /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(l))
    .filter((m) => m && m[2].trim() !== '')
    .map((m) => m[1]),
);

const missingRequired = required.filter((k) => !present.has(k));
const toAdd = Object.keys(generated).filter((k) => !present.has(k));

if (!checkOnly && toAdd.length > 0) {
  const block = `${text.endsWith('\n') || text === '' ? '' : '\n'}\n# Sakaime Zetaris stack (generated by infra/zetaris/scripts/secrets.mjs)\n${toAdd.map((k) => `${k}=${generated[k]()}`).join('\n')}\n`;
  appendFileSync(envPath, block, { mode: 0o600 });
}

console.log(`added: ${checkOnly ? '(check only)' : toAdd.join(', ') || 'none'}`);
if (missingRequired.length > 0) {
  console.log(`missing, add from your Zetaris download page: ${missingRequired.join(', ')}`);
  process.exitCode = 3;
}
