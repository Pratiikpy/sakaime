/**
 * Runs the FDA summary parser over the 12 fixtures, scores it against the hand-labelled gold, and writes
 * tests/extraction/RESULTS.md. Usage: npx tsx tests/extraction/run-measurement.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { formatReport } from "../../src/extraction/measure.ts";
import { formatReport as format } from "../../src/extraction/measure.ts";
import { loadAdjudication, loadGold, measureFda, runAllText, runDevelopmentPdfs, runHeldOut } from "./measurement.ts";

const FIRST_RUN = [
  "| field | gold | extracted | correct | wrong | missed | precision | recall |",
  "|---|---|---|---|---|---|---|---|",
  "| device version strings | 1 | 1 | 1 | 0 | 0 | 1.000 | 1.000 |",
  "| age minimum in the indications | 1 | 0 | 0 | 0 | 1 | n/a | 0.000 |",
  "| age minimum of the study population | 3 | 2 | 2 | 0 | 1 | 1.000 | 0.667 |",
  "| care settings in the indications | 3 | 3 | 3 | 0 | 0 | 1.000 | 1.000 |",
  "| study sample sizes (recall only) | 7 | 18 | 5 | +13 other | 2 | n/a | 0.714 |",
  "| study site counts (recall only) | 3 | 4 | 3 | +1 other | 0 | n/a | 1.000 |",
  "| performance statements (metric, value, kind) | 16 | 17 | 11 | 6 | 5 | 0.647 | 0.688 |",
  "| headline results (overall observed figures) | 10 | 12 | 8 | 4 | 2 | 0.667 | 0.800 |",
].join("\n");

const gold = loadGold();
const adjudication = loadAdjudication();
const runs = await runAllText();
const report = measureFda(gold, runs, adjudication);

const results = report.perField.find((f) => f.field.startsWith("performance"));
const lines: string[] = [];
lines.push("# Extraction results");
lines.push("");
lines.push("Generated by `npx tsx tests/extraction/run-measurement.ts`. Do not edit by hand.");
lines.push("");
lines.push("## What was measured");
lines.push("");
lines.push("The FDA summary parser (`src/extraction/fda-summary.ts`) was run over the 12 summaries in `research/feasibility/fixtures/fda` (the `pdftotext -layout` text of the real FDA PDFs, pages split on form feeds) and scored against `tests/extraction/gold/fda-gold.json`.");
lines.push("");
lines.push("- These 12 documents are the DEVELOPMENT set: the parser was changed while looking at them, so these scores are in-sample.");
lines.push("- Gold: labelled by ONE reader, who also wrote the extractor and is not blind to it. The labels were written from the documents; they have not been checked by a second reader. Treat the scores as a development measurement, not an independent one.");
lines.push("- A value counts as extracted only if it passed BOTH checks (quote-exists and semantic support). Tables are not parsed and are not in the gold (see the limits below).");
lines.push("- Precision is reported where the gold is meant to be exhaustive. For sample sizes and site counts the gold lists the principal counts only, so only recall is a score and the other counts are listed as `other`.");
lines.push("- Performance figures the gold did not name were read against their passage and judged (`tests/extraction/gold/fda-adjudication.json`); precision credits the ones judged correct.");
lines.push("- Only 1 of the 12 PDFs is committed (DEN180001); the pdfjs path is exercised on it in the tests. The text fixtures are the same documents run through `pdftotext`, so the scores here describe the parser on that text, not pdfjs on all 12 files (see the pdfjs section).");
lines.push("");
lines.push("## Per-field scores (12 documents)");
lines.push("");
lines.push(formatReport(report));
lines.push("");
if (results?.adjudicated) {
  lines.push(`Performance figures: ${results.note ?? ""}. Extras judged correct ${results.adjudicated.correct}, incorrect ${results.adjudicated.incorrect}, not yet judged ${results.adjudicated.unadjudicated}. Of ${results.intervalAgreement?.matched ?? 0} matched figures that have a confidence interval in the gold, ${results.intervalAgreement?.agree ?? 0} carry the same interval.`);
  lines.push("");
}
const devPdf = await runDevelopmentPdfs(process.env.SAKAIME_FDA_PDF_DIR);
if (devPdf) {
  lines.push("## The same 12 documents read through pdfjs instead of pdftotext");
  lines.push("");
  lines.push("The 12 PDFs were fetched again from the URLs in `research/feasibility/fixtures/MANIFEST.md` (sha256 checked against the manifest) and read with `readPdf`; the same gold applies. Reading order, spacing and ligature handling differ from pdftotext, so this is the number that describes the production path.");
  lines.push("");
  lines.push(format(devPdf.report));
  lines.push("");
  lines.push("The one wrong study-age minimum is K253265: pdfjs reads a jumbled fragment of a criteria table ('adults/transitional adults >= 18 years ... Slice thickness'), which repeats the 18 of the indication; the gold does not list it as a study limit. The four missed performance figures are the two AUC labels printed inside a figure (DEN200055) and two reader-arm figures (K240301) whose sentences pdfjs orders differently from pdftotext; the cause is reading order, not the rules.");
  lines.push("");
}
lines.push("## Documents the parser was not developed on (pdfjs, 5 PDFs)");
lines.push("");
lines.push("Five 510(k) summaries fetched after the parser was written (K253801, K252360, K253825, K250680, K253163; URLs and labels in `gold/fda-heldout-gold.json`). They were read through pdfjs, not pdftotext. The PDFs are not committed; `SAKAIME_HELDOUT_DIR=<dir> npx tsx tests/extraction/run-heldout.ts --verbose` reproduces the numbers.");
lines.push("");
lines.push("These are not a blind test. The same reader labelled them from the text before the first run, and the reading led to four additions made before that run (PPA/NPA as metrics, the \u2265 symbol in age limits, the repair of ligature glyphs, and attributing figures that follow the word predicate). The first run then exposed further faults, which were fixed. So the first-run table is the closest thing here to an unseen result, and the final table is a development result.");
lines.push("");
lines.push("First run, before the fixes that run exposed (extra figures not yet adjudicated, so counted wrong):");
lines.push("");
lines.push(FIRST_RUN);
lines.push("");
const held = await runHeldOut(process.env.SAKAIME_HELDOUT_DIR);
if (held) {
  lines.push("After the fixes (extras adjudicated; every extra was a real subgroup figure from K253801):");
  lines.push("");
  lines.push(format(held.report));
  lines.push("");
  lines.push("What the first run exposed: a version number printed in the predicate's block was read as the subject's (K253825); a subject and predicate version in one table row (K252360); a lost \u2265 glyph on one page and the symbol on another (K250680); positive and negative percent agreement used instead of sensitivity and specificity (K250680); subgroup tables read as overall figures (K253801); a sentence giving the subject's and the predicate's figures together (K253163), where the predicate's must not be used.");
} else {
  lines.push("(The held-out run was not repeated when this file was generated: SAKAIME_HELDOUT_DIR was not set.)");
}
lines.push("");
lines.push("## The two checks, reported apart");
lines.push("");
const c = report.checks;
lines.push("| | count |");
lines.push("|---|---|");
lines.push(`| assertions proposed by the parser | ${c.proposed} |`);
lines.push(`| discarded for having no quote | ${c.discardedUnquoted} |`);
lines.push(`| check 1, quote-exists: passed | ${c.quote.passed} |`);
lines.push(`| check 1, quote-exists: failed (dropped) | ${c.quote.failed} |`);
lines.push(`| check 2, semantic support: PASS | ${c.support.pass} |`);
lines.push(`| check 2, semantic support: FAIL | ${c.support.fail} |`);
lines.push(`| check 2, semantic support: UNCHECKED | ${c.support.unchecked} |`);
lines.push("");
lines.push("The quote-exists check is satisfied by construction for these extractions, because the parser quotes text it read from the page. It is therefore not evidence about the parser; it is evidence that the stored page text and the anchors agree. The semantic check is the one that rejects things here: figures that belong to a predicate device, a prespecified goal read as a result, and figures on a page that sets the proposed and the predicate device side by side.");
lines.push("");
lines.push("## Per document");
lines.push("");
lines.push("| document | proposed | usable (both checks passed) |");
lines.push("|---|---|---|");
for (const [id, d] of Object.entries(report.perDoc)) lines.push(`| ${id} | ${d.proposed} | ${d.usable} |`);
lines.push("");
lines.push("Fields searched for and not found stay absent; the parser never fills one in. For each document the status of every searched field is in `FdaSummaryExtraction.fields`.");
lines.push("");
lines.push("## Known limits, from reading the documents");
lines.push("");
lines.push("- Results that exist only in tables are not extracted. EyeArt K200667 states its pivotal sensitivity and specificity only in a stacked-cell table (24 table rows with several values were seen and counted, none extracted). A table needs cell geometry and column headers; this parser reads sentences and single-value rows only.");
lines.push("- Text-layer damage defeats some sentences. DEN170073 and DEN200055 carry recognition errors ('Trnth', 'repo1ts', 'res ectivel y', 'emolled'); a quote that reproduces the damaged characters still matches, but a sentence broken inside a number or a metric word is not read. In DEN200080, 14 of 25 PDF pages have no text layer at all (scans) and nothing is read from them.");
lines.push("- A lost comparison glyph hides the direction of a limit. The pdftotext text of K232699 reads 'age  18' (the greater-or-equal sign is missing), so no age limit is extracted from that text and the parser does not guess a direction; pdfjs keeps the glyph and reads the limit from the PDF. K250680's form page loses the sign too, and its summary page keeps it.");
lines.push("- Comparison tables that set the proposed and predicate devices side by side are flagged `comparison_table`; figures on those pages are UNCHECKED, not used.");
lines.push("- No fixture states that clinical testing was not conducted, so that rule is covered by a unit test on a constructed sentence only.");
lines.push("- Clinical conditions in the indications (for example 'diabetic retinopathy') are not extracted; only age, setting, purpose and population group terms are.");
lines.push("");
writeFileSync(join(import.meta.dirname, "RESULTS.md"), lines.join("\n"));
console.log(formatReport(report));
