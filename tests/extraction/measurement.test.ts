import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { formatReport, measureFda, type MeasureReport } from "../../src/extraction/measure.ts";
import { loadAdjudication, loadGold, runAllText } from "./measurement.ts";

/**
 * Regression floors on the in-sample measurement (the 12 development summaries). They sit a little under the
 * measured figures so a change that loses a field fails here. The honest numbers, including the held-out documents,
 * are in RESULTS.md.
 */
let report: MeasureReport;
beforeAll(async () => {
  const gold = loadGold();
  const runs = await runAllText();
  report = measureFda(gold, runs, loadAdjudication());
}, 120_000);

const field = (name: string) => {
  const f = report.perField.find((x) => x.field.startsWith(name));
  if (!f) throw new Error(`no field ${name}`);
  return f;
};

describe("extraction measurement against the hand-labelled gold", () => {
  it("reads every version string it should and none it should not", () => {
    expect(field("device version").precision).toBe(1);
    expect(field("device version").recall).toBe(1);
  });

  it("reads the indication's age limit and every labelled care setting", () => {
    expect(field("age minimum in the indications").recall).toBe(1);
    expect(field("age minimum in the indications").precision).toBe(1);
    expect(field("care settings").recall).toBeGreaterThanOrEqual(0.85);
    expect(field("care settings").precision).toBe(1);
  });

  it("finds the principal counts and every trial identifier", () => {
    expect(field("study sample sizes").recall).toBeGreaterThanOrEqual(0.9);
    expect(field("study site counts").recall).toBeGreaterThanOrEqual(0.85);
    expect(field("registered trial identifiers").recall).toBe(1);
    expect(field("registered trial identifiers").precision).toBe(1);
  });

  it("reads performance statements with a high precision once extras are adjudicated", () => {
    const f = field("performance statements");
    expect(f.precision ?? 0).toBeGreaterThanOrEqual(0.9);
    expect(f.recall ?? 0).toBeGreaterThanOrEqual(0.9);
    expect(f.adjudicated?.unadjudicated).toBe(0);
    expect(f.intervalAgreement?.agree).toBe(f.intervalAgreement?.matched);
  });

  it("separates the overall observed figures from the rest", () => {
    expect(report.headline.precision ?? 0).toBeGreaterThanOrEqual(0.9);
    expect(report.headline.recall ?? 0).toBeGreaterThanOrEqual(0.9);
  });

  it("reports the two checks apart and keeps the counters consistent", () => {
    const c = report.checks;
    expect(c.quote.passed + c.quote.failed).toBe(c.proposed);
    expect(c.support.pass + c.support.fail + c.support.unchecked).toBe(c.quote.passed);
  });

  it("formats a table", () => {
    expect(formatReport(report)).toContain("| headline results");
  });

  it("has a RESULTS.md that was generated by the runner", () => {
    const path = join(import.meta.dirname, "RESULTS.md");
    expect(existsSync(path)).toBe(true);
    expect(readFileSync(path, "utf8")).toContain("Per-field scores");
  });
});
