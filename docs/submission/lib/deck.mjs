// Assembles the slides into one HTML document and the speaker notes. Used by build-deck.mjs and check-numbers.mjs.
import { CSS } from "./css.mjs";
import { ctx } from "./ctx.mjs";
import { esc } from "./ui.mjs";
import { part1 } from "../slides/part1.mjs";
import { part2 } from "../slides/part2.mjs";
import { part3 } from "../slides/part3.mjs";
import { part4 } from "../slides/part4.mjs";
import { part5 } from "../slides/part5.mjs";

const strip = (html) =>
  html
    .replace(/<style[\s\S]*?<\/style>/g, " ")
    .replace(/<svg[\s\S]*?<\/svg>/g, (m) => (m.match(/<text[^>]*>([\s\S]*?)<\/text>/g) ?? []).map((t) => t.replace(/<[^>]+>/g, " ")).join(" "))
    .replace(/<[^>]+>/g, " ")
    .replace(/&#\d+;/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&middot;/g, "·")
    .replace(/&rarr;/g, "->")
    .replace(/&mdash;/g, "-")
    .replace(/\s+/g, " ")
    .trim();

export function buildAll() {
  const defs = [...part1, ...part2, ...part3, ...part4, ...part5];
  const total = defs.length;
  const slides = defs.map((d, i) => {
    ctx.derived = [];
    const inner = d.html();
    const derived = ctx.derived.slice();
    const n = i + 1;
    const title = (inner.match(/<h2[^>]*>([\s\S]*?)<\/h2>/) ?? inner.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) ?? [, d.id])[1].replace(/<[^>]+>/g, "");
    const srcs = d.sources.filter((s) => !s.startsWith("ui/src"));
    const shown = srcs.slice(0, 3).join("  ·  ") + (srcs.length > 3 ? `  ·  +${srcs.length - 3}` : "");
    const html = `
<section class="slide ${d.dark ? "dark" : ""} ${d.tint ? "tint" : ""}" id="s${String(n).padStart(2, "0")}" data-n="${n}">
<!-- SPEAKER NOTES ${n}: ${esc(d.notes).replace(/--/g, "- -")} -->
<header class="top"><span class="brand"><i></i>Sakaime</span><span class="sect">${esc(d.section)}</span>${d.crit ? `<span class="crit">${esc(d.crit)}</span>` : ""}<span class="pg">${String(n).padStart(2, "0")} / ${total}</span></header>
<div class="body">${inner}</div>
<footer class="foot"><span>Sources: ${esc(shown)}</span><span class="cls">${esc(d.cls ?? "")}</span></footer>
</section>`;
    return { n, id: d.id, section: d.section, crit: d.crit ?? "", title, html, text: strip(inner), notes: d.notes, sources: d.sources, derived, extra: d.allow ?? [] };
  });
  return { slides, css: CSS, total };
}

export function renderDocument({ slides, css }) {
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Sakaime: know where the evidence stops</title>
<meta name="viewport" content="width=1920"><style>${css}
html { zoom: 1; }
</style></head><body>
${slides.map((s) => s.html).join("\n")}
</body></html>`;
}

export function speakerNotes({ slides }) {
  return `# Sakaime deck: speaker notes

One entry per slide of \`sakaime-deck.pdf\`, in order. Generated by \`build-deck.mjs\` from the slide sources; edit the notes in \`slides/\`, not here.

${slides.map((s) => `## ${s.n}. ${s.title}\n\n${s.notes}\n`).join("\n")}`;
}
